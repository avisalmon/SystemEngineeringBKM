"""Render the course book to static, right-to-left HTML pages.

    python -m sebkm render course           write the pages
    python -m sebkm render course --check   only check that the pages on disk are up to date

The pages are committed next to their Markdown sources, so GitHub Pages serves them as they are:

    course/README.md             ->  course/index.html             the front page of the book
    course/NN_<name>/README.md   ->  course/NN_<name>/index.html   the chapter of meeting NN
    course/NN_<name>/slides.md   ->  course/NN_<name>/slides.html  the slide deck of meeting NN

Every relative link is checked. A link to a rendered source becomes a link to its page, a link to any
other file of the repository opens that file on GitHub, and a missing file or section is an error.
The look lives in assets/ (book.css, book.js, deck.css, deck.js); diagrams use the vendored Mermaid.
"""

