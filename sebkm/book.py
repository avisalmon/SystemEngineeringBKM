class BookError(Exception):
    """A problem in the book sources, such as a broken link or a missing heading."""


def esc(text: str) -> str:
    return html.escape(text, quote=True)


def read(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8-sig").replace("\r\n", "\n")


def version(rel: str) -> str:
    """A short content hash for cache busting, the same on every OS whatever the line endings."""
    data = (ROOT / rel).read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(data).hexdigest()[:10]


def rel_url(here: str, there: str) -> str:
    """The relative URL from one repository file to another, both POSIX paths from the root."""
    base, target = here.split("/")[:-1], there.split("/")
    same = 0
    while same < len(base) and same < len(target) - 1 and base[same] == target[same]:
        same += 1
    return "/".join([".."] * (len(base) - same) + target[same:])


def github_slug(text: str) -> str:
    """The id GitHub gives a heading: lower case, punctuation dropped, each space made a hyphen."""
    kept = []
    for ch in text.lower():
        category = unicodedata.category(ch)
        if ch in " -" or category[0] in "LM" or category in ("Nd", "Nl", "Pc"):
            kept.append(ch)
    return "".join(kept).replace(" ", "-")


class Slugger:
    """Unique heading ids, with repeated headings numbered the way GitHub numbers them."""

    def __init__(self) -> None:
        self.seen: dict[str, int] = {}

    def slug(self, text: str) -> str:
        base = result = github_slug(text)
        while result in self.seen:
            self.seen[base] += 1
            result = f"{base}-{self.seen[base]}"
        self.seen[result] = 0
        return result


def plain(inline: Token) -> str:
    """The text of an inline token, without its markup."""
    parts = []
    for child in inline.children or []:
        if child.type in ("text", "code_inline"):
            parts.append(child.content)
        elif child.type in ("softbreak", "hardbreak"):
            parts.append(" ")
    return "".join(parts)


def strong_text(inline: Token) -> str:
    """The text of the first bold run of an inline token."""
    kids = inline.children or []
    for i, kid in enumerate(kids):
        if kid.type == "strong_open":
            words = []
            for k in kids[i + 1:]:
                if k.type == "strong_close":
                    break
                if k.type in ("text", "code_inline"):
                    words.append(k.content)
            return "".join(words)
    return ""


def _label_at(inline: Token | None) -> int | None:
    """Where the bold label of a paragraph starts among its children, skipping empty text."""
    if inline is None or inline.type != "inline" or not inline.children:
        return None
    kids, i = inline.children, 0
    while i < len(kids) and kids[i].type == "text" and not kids[i].content.strip():
        i += 1
    if len(kids) - i >= 3 and (kids[i].type, kids[i + 1].type, kids[i + 2].type) == (
        "strong_open", "text", "strong_close"
    ):
        return i
    return None


def lead_label(inline: Token | None) -> str | None:
    """The bold label a paragraph opens with, such as **המסר:**, without its colon."""
    i = _label_at(inline)
    if i is None:
        return None
    kids = inline.children
    label = kids[i + 1].content.strip()
    if label.endswith(":"):
        return label[:-1].strip()
    if len(kids) > i + 3 and kids[i + 3].type == "text" and kids[i + 3].content.startswith(":"):
        return label
    return None


def drop_label(inline: Token) -> Token:
    """A copy of an inline token without the bold label it opens with."""
    kids = list((inline.children or [])[(_label_at(inline) or 0) + 3:])
    if kids and kids[0].type == "text":
        kids[0] = kids[0].copy(content=kids[0].content.lstrip(":").lstrip())
    return inline.copy(children=kids)


def block_end(tokens: list[Token], start: int) -> int:
    """The index just after the block that starts at tokens[start]."""
    depth, i = 0, start
    while True:
        depth += tokens[i].nesting
        i += 1
        if depth <= 0:
            return i


def split_title(text: str) -> tuple[str, str]:
    """Split a title such as "פרק 1: מבוא" into its short prefix and the rest."""
    kicker, sep, rest = text.partition(": ")
    if sep and rest.strip() and len(kicker) <= 24:
        return kicker.strip(), rest.strip()
    return "", text.strip()


def shorten(text: str, limit: int = 200) -> str:
    text = " ".join(text.split())
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",;:") + "…"


def _fence(self, tokens, idx, options, env):
    token = tokens[idx]
    lang = token.info.split()[0] if token.info.strip() else ""
    code = html.escape(token.content, quote=False)
    if lang == "mermaid":
        return f'<figure class="diagram"><pre class="mermaid">{code}</pre></figure>\n'
    attr = f' class="language-{esc(lang)}"' if lang else ""
    return f'<pre class="code" dir="ltr"><code{attr}>{code}</code></pre>\n'


def _table_open(self, tokens, idx, options, env):
    cols = 0
    for token in tokens[idx + 1:]:
        if token.type == "th_open":
            cols += 1
        elif token.type == "tr_close":
            break
    return f'<div class="table-wrap" style="--cols:{cols}">\n' + self.renderToken(tokens, idx, options, env)


def _table_close(self, tokens, idx, options, env):
    return self.renderToken(tokens, idx, options, env) + "</div>\n"


def _heading_close(self, tokens, idx, options, env):
    opener = tokens[idx - 2]
    hid = opener.attrGet("id")
    anchor = ""
    if hid and opener.tag in ("h2", "h3"):
        anchor = f'<a class="anchor" href="#{esc(str(hid))}" aria-label="קישור לסעיף">#</a>'
    return anchor + self.renderToken(tokens, idx, options, env)


def _html_block(self, tokens, idx, options, env):
    content = tokens[idx].content
    return "" if COMMENTS.fullmatch(content) else content


def make_markdown() -> MarkdownIt:
    md = MarkdownIt("commonmark", {"html": True, "linkify": True})
    md.enable(["table", "strikethrough", "linkify"])
    md.linkify.set({"fuzzy_link": False, "fuzzy_email": False})
    for name, rule in (
        ("fence", _fence),
        ("table_open", _table_open),
        ("table_close", _table_close),
        ("heading_close", _heading_close),
        ("html_block", _html_block),
    ):
        md.add_render_rule(name, rule)
    return md


@dataclass
class Slide:
    number: int
    title: str
    tokens: list[Token]


@dataclass
class Doc:
    src: str  # the Markdown source, a POSIX path from the repository root
    out: str  # the generated page
    kind: str  # "front", "chapter" or "deck"
    number: int  # the meeting number; 0 for the front page
    text: str
    h1: str = ""
    tokens: list[Token] = field(default_factory=list)
    ids: set[str] = field(default_factory=set)
    slides: list[Slide] = field(default_factory=list)
    footer: list[Token] = field(default_factory=list)

    def token_lists(self) -> list[list[Token]]:
        return [self.tokens, *(slide.tokens for slide in self.slides), self.footer]

    def has_diagrams(self) -> bool:
        return any(
            token.type == "fence" and token.info.split()[:1] == ["mermaid"]
            for tokens in self.token_lists()
            for token in tokens
        )


def split_deck(text: str) -> tuple[str, list[str], str]:
    """Split a deck at its "---" lines (outside code fences) into the header, the slides and the footer."""
    sections: list[str] = []
    lines: list[str] = []
    fence = ""
    for line in text.split("\n"):
        match = FENCE_RE.match(line)
        if fence:
            if match and match.group(1)[0] == fence[0] and len(match.group(1)) >= len(fence) \
                    and not line.strip().strip(fence[0]):
                fence = ""
        elif match:
            fence = match.group(1)
        elif line.rstrip() == "---":
            sections.append("\n".join(lines))
            lines = []
            continue
        lines.append(line)
    sections.append("\n".join(lines))
    head, slides = sections[0], sections[1:]
    footer = slides.pop() if slides and not slides[-1].lstrip().startswith("#") else ""
    return head, slides, footer


def mark_callouts(tokens: list[Token]) -> None:
    """Give "הערת עורך" and "שימו לב" blockquotes the classes that style them as callouts."""
    for i in range(len(tokens) - 2):
        if tokens[i].type == "blockquote_open" and tokens[i + 1].type == "paragraph_open":
            cls = CALLOUTS.get(lead_label(tokens[i + 2]) or "")
            if cls:
                tokens[i].attrSet("class", cls)


class Book:
    """The course book: every source parsed and every link checked, ready to render."""

    def __init__(self) -> None:
        self.md = make_markdown()
        self.versions: dict[str, str] = {}
        self.docs = self.discover()
        self.by_src = {doc.src: doc for doc in self.docs}
        self.front = self.docs[0]
        self.chapters = {doc.number: doc for doc in self.docs if doc.kind == "chapter"}
        self.decks = {doc.number: doc for doc in self.docs if doc.kind == "deck"}
        for doc in self.docs:
            self.parse(doc)
        for doc in self.docs:
            for tokens in doc.token_lists():
                self.fix_links(doc, tokens)
        self.topics = self.read_topics()

    @staticmethod
    def discover() -> list[Doc]:
        if not (ROOT / "course" / "README.md").is_file():
            raise BookError("course/README.md is missing")
        docs = [Doc("course/README.md", "course/index.html", "front", 0, read("course/README.md"))]
        folders = sorted(
            p for p in (ROOT / "course").iterdir() if p.is_dir() and re.fullmatch(r"\d\d_[\w-]+", p.name)
        )
        for folder in folders:
            base, number = f"course/{folder.name}", int(folder.name[:2])
            if (folder / "README.md").is_file():
                docs.append(Doc(f"{base}/README.md", f"{base}/index.html", "chapter", number, read(f"{base}/README.md")))
            if (folder / "slides.md").is_file():
                docs.append(Doc(f"{base}/slides.md", f"{base}/slides.html", "deck", number, read(f"{base}/slides.md")))
        return docs

    def parse(self, doc: Doc) -> None:
        if doc.kind == "deck":
            head, slides, footer = split_deck(doc.text)
            doc.tokens = self.md.parse(head)
            for number, section in enumerate(slides, 1):
                first, _, body = section.strip("\n").partition("\n")
                match = SLIDE_RE.match(first)
                if not match or int(match.group(1)) != number:
                    raise BookError(f'{doc.src}: slide {number} must start with "## שקף {number}: <title>"')
                doc.slides.append(Slide(number, match.group(2), self.md.parse(body)))
            if not doc.slides:
                raise BookError(f"{doc.src}: the deck has no slides")
            doc.footer = self.md.parse(footer) if footer.strip() else []
            doc.ids = {str(slide.number) for slide in doc.slides}
        else:
            doc.tokens = self.md.parse(doc.text)
            slugger = Slugger()
            for i, token in enumerate(doc.tokens):
                if token.type == "heading_open":
                    hid = slugger.slug(plain(doc.tokens[i + 1]))
                    token.attrSet("id", hid)
                    doc.ids.add(hid)
        doc.h1 = plain(self.split_head(doc)[0]).strip()
        for tokens in doc.token_lists():
            mark_callouts(tokens)

    def split_head(self, doc: Doc) -> tuple[Token, list[Token], int]:
        """The H1, the paragraphs of the blockquote under it, and the index where the body starts."""
        tokens, i = doc.tokens, 0
        while i < len(tokens) and tokens[i].type == "html_block" and COMMENTS.fullmatch(tokens[i].content):
            i += 1
        if i + 2 >= len(tokens) or tokens[i].type != "heading_open" or tokens[i].tag != "h1":
            raise BookError(f"{doc.src}: the file must start with a level-1 heading")
        h1, i = tokens[i + 1], i + 3
        paras: list[Token] = []
        if i < len(tokens) and tokens[i].type == "blockquote_open":
            end = block_end(tokens, i)
            paras = [token for token in tokens[i:end] if token.type == "inline"]
            i = end
        return h1, paras, i

    @staticmethod
    def split_footer(tokens: list[Token], start: int) -> tuple[int, list[Token]]:
        """The rights paragraphs after the last top-level rule, when nothing else follows it."""
        for i in range(len(tokens) - 1, start - 1, -1):
            if tokens[i].type == "hr" and tokens[i].level == 0:
                tail = tokens[i + 1:]
                if tail and all(t.type in ("paragraph_open", "inline", "paragraph_close") for t in tail):
                    return i, tail
                break
        return len(tokens), []

    def fix_links(self, doc: Doc, tokens: list[Token]) -> None:
        for token in tokens:
            for child in token.children or []:
                if child.type == "link_open":
                    self.fix_link(doc, child)
                elif child.type == "image":
                    self.check_image(doc, child)

    def fix_link(self, doc: Doc, link: Token) -> None:
        href = str(link.attrGet("href") or "")
        if link.markup == "linkify" or re.match(r"https?://", href):
            link.attrSet("target", "_blank")
            link.attrSet("rel", "noopener")
            if link.markup == "linkify":
                link.attrSet("dir", "ltr")
            return
        if href.startswith("mailto:"):
            return
        path, _, frag = href.partition("#")
        path, frag = unquote(path), unquote(frag)
        if not path:
            if frag and frag not in doc.ids:
                raise BookError(f"{doc.src}: a link to a missing section #{frag}")
            link.attrSet("href", f"#{frag}")
            return
        url = self.resolve(doc, path, frag)
        link.attrSet("href", url)
        if url.startswith("https://"):
            link.attrSet("target", "_blank")
            link.attrSet("rel", "noopener")

    def resolve(self, doc: Doc, path: str, frag: str) -> str:
        """Where a relative link of the book points on the site."""
        target = posixpath.normpath(posixpath.join(posixpath.dirname(doc.src), path))
        hash_ = f"#{frag}" if frag else ""
        if target == ".." or target.startswith("../"):
            raise BookError(f"{doc.src}: the link {path} leaves the repository")
        if target in (".", "README.md"):  # the guide itself: on the site, its start page
            return rel_url(doc.out, "index.html") + hash_
        page = self.by_src.get(target) or self.by_src.get(f"{target}/README.md")
        if page is not None:
            if frag and frag not in page.ids:
                raise BookError(f"{doc.src}: a link to a missing section {page.src}#{frag}")
            return hash_ if page is doc and hash_ else rel_url(doc.out, page.out) + hash_
        full = ROOT / target
        if not full.exists():
            raise BookError(f"{doc.src}: a link to a missing file {target}")
        if full.is_file() and target.endswith(".html"):  # a page of the site itself
            return rel_url(doc.out, target) + hash_
        kind = "tree" if full.is_dir() else "blob"
        return f"{REPO_URL}/{kind}/main/{quote(target)}" + (f"#{quote(frag)}" if frag else "")

    def check_image(self, doc: Doc, image: Token) -> None:
        src = str(image.attrGet("src") or "")
        if not re.match(r"(https?:|data:)", src):
            target = posixpath.normpath(posixpath.join(posixpath.dirname(doc.src), unquote(src)))
            if not (ROOT / target).is_file():
                raise BookError(f"{doc.src}: a missing image {target}")
        image.attrSet("loading", "lazy")

    def read_topics(self) -> dict[int, str]:
        """Meeting topics from the contents table of the front page, for the "coming soon" cards."""
        topics: dict[int, str] = {}
        row: list[Token] | None = None
        for token in self.front.tokens:
            if token.type == "tr_open":
                row = []
            elif token.type == "tr_close":
                if row and len(row) >= 3:
                    match = MEETING_RE.fullmatch(plain(row[0]).strip())
                    topic = strong_text(row[2]).strip().rstrip(":").strip()
                    if match and topic:
                        topics[int(match.group(1))] = topic
                row = None
            elif token.type == "inline" and row is not None:
                row.append(token)
        return topics

    # Shared rendering helpers.

    def asset(self, doc: Doc, rel: str) -> str:
        """The URL of a shared asset from a page, with a content hash so browsers never keep a stale copy."""
        if rel not in self.versions:
            if not (ROOT / rel).is_file():
                raise BookError(f"{rel} is missing")
            self.versions[rel] = version(rel)
        return f"{rel_url(doc.out, rel)}?v={self.versions[rel]}"

    def inline(self, token: Token) -> str:
        return self.md.renderer.renderInline(token.children or [], self.md.options, {})

    def blocks(self, tokens: list[Token]) -> str:
        return self.md.renderer.render(tokens, self.md.options, {})

    def head_parts(self, paras: list[Token]) -> dict:
        """Sort the paragraphs of a header blockquote into the lead, meta pills, buttons and rights."""
        lead_word = "בפרק הזה:"
        parts: dict = {"lead": "", "lead_text": "", "meta": [], "meta_text": [], "actions": [], "rights": []}
        for para in paras:
            text = plain(para).strip()
            action = ACTION_RE.fullmatch(para.content.strip())
            if text.startswith("כל הזכויות"):
                parts["rights"].append(self.inline(para))
            elif text.startswith(lead_word) and not parts["lead"]:
                rendered = self.inline(para)
                if rendered.startswith(lead_word):
                    rendered = f"<strong>{lead_word}</strong>{rendered[len(lead_word):]}"
                parts["lead"], parts["lead_text"] = rendered, text[len(lead_word):].strip()
            elif action:
                link = next(child for child in para.children or [] if child.type == "link_open")
                parts["actions"].append({
                    "primary": action.group("href").split("#")[0].endswith("slides.md"),
                    "title": action.group("label").strip(),
                    "text": action.group("text").strip(),
                    "href": str(link.attrGet("href")),
                })
            else:
                parts["meta"].append(self.inline(para))
                parts["meta_text"].append(text)
        if not parts["lead"] and parts["meta"]:
            parts["lead"], parts["lead_text"] = parts["meta"].pop(0), parts["meta_text"].pop(0)
        parts["actions"].sort(key=lambda action: not action["primary"])
        return parts

    @staticmethod
    def button(action: dict) -> str:
        href = action["href"]
        cls = "btn primary" if action["primary"] else "btn ghost"
        icon = ICON_SLIDES if href.split("#")[0].endswith("slides.html") else ICON_BOOK
        title = f' title="{esc(action["title"])}"' if action.get("title") else ""
        new_tab = ' target="_blank" rel="noopener"' if href.startswith("https://") else ""
        return f'<a class="{cls}" href="{esc(href)}"{title}{new_tab}>{icon}<span>{esc(action["text"])}</span></a>'

    def page_head(self, doc: Doc, parts: dict, eyebrow: str, title: str) -> str:
        out = ['<header class="page-head">']
        if doc.kind == "chapter":
            out.append(f'<span class="page-num" aria-hidden="true">{doc.number}</span>')
        out.append(f'<p class="eyebrow">{esc(eyebrow)}</p>')
        out.append(f"<h1>{esc(title)}</h1>")
        if parts["lead"]:
            out.append(f'<p class="lead">{parts["lead"]}</p>')
        if parts["meta"]:
            out.append('<ul class="meta">' + "".join(f"<li>{meta}</li>" for meta in parts["meta"]) + "</ul>")
        if parts["actions"]:
            out.append('<div class="actions">' + "".join(self.button(a) for a in parts["actions"]) + "</div>")
        out += [f'<p class="head-rights">{rights}</p>' for rights in parts["rights"]]
        out.append("</header>")
        return "\n".join(out)

    @staticmethod
    def tocs(body: list[Token], title: str) -> tuple[str, str]:
        """The side table of contents (wide screens) and the folding one (narrow screens)."""
        entries = [
            (token.tag, str(token.attrGet("id")), esc(plain(body[i + 1]).strip()))
            for i, token in enumerate(body)
            if token.type == "heading_open" and token.level == 0 and token.tag in ("h2", "h3")
        ]
        if not any(tag == "h2" for tag, _, _ in entries):
            return "", ""
        side = [f'<nav class="toc-side" aria-label="{esc(title)}">', f'<p class="toc-title">{esc(title)}</p>', "<ol>"]
        in_h2 = in_sub = False
        for tag, hid, label in entries:
            link = f'<a href="#{esc(hid)}">{label}</a>'
            if tag == "h2":
                if in_sub:
                    side.append("</ol>")
                if in_h2:
                    side.append("</li>")
                side.append(f'<li class="h2">{link}')
                in_h2, in_sub = True, False
            elif in_h2:
                if not in_sub:
                    side.append("<ol>")
                    in_sub = True
                side.append(f"<li>{link}</li>")
        side += (["</ol>"] if in_sub else []) + ["</li>", "</ol>", "</nav>"]
        mobile = ['<details class="toc-mobile">', "<summary>תוכן העניינים</summary>", "<ol>"]
        mobile += [f'<li><a href="#{esc(hid)}">{label}</a></li>' for tag, hid, label in entries if tag == "h2"]
        mobile += ["</ol>", "</details>"]
        return "\n".join(side), "\n".join(mobile)

    def pager(self, doc: Doc) -> str:
        def card(target: str, cls: str, small: str, title: str) -> str:
            text = f"<span><small>{esc(small)}</small><b>{esc(title)}</b></span>"
            inner = ICON_PREV + text if cls == "prev" else text + ICON_NEXT
            return f'<a class="pg {cls}" rel="{cls}" href="{esc(rel_url(doc.out, target))}">{inner}</a>'

        numbers = sorted(self.chapters)
        cards = []
        if doc.kind == "front":
            cards.append(card("index.html", "prev", "הקודם", f"דף הבית: {GUIDE}"))
            if numbers:
                first = self.chapters[numbers[0]]
                cards.append(card(first.out, "next", "הבא", first.h1))
        else:
            k = numbers.index(doc.number)
            if k:
                before = self.chapters[numbers[k - 1]]
                cards.append(card(before.out, "prev", "הקודם", before.h1))
            else:
                cards.append(card(self.front.out, "prev", "הקודם", f"{BOOK}: על הספר ותוכן העניינים"))
            if k + 1 < len(numbers):
                after = self.chapters[numbers[k + 1]]
                cards.append(card(after.out, "next", "הבא", after.h1))
            elif doc.number + 1 in self.topics:
                cards.append(
                    '<div class="pg next soon"><span><small>הבא · בקרוב</small>'
                    f"<b>פרק {doc.number + 1}: {esc(self.topics[doc.number + 1])}</b></span></div>"
                )
        return '<nav class="pager" aria-label="ניווט בין הפרקים">' + "".join(cards) + "</nav>"

    def top(self, doc: Doc, progress: bool) -> str:
        links = []
        if doc.kind == "front":
            links.append(("index.html", "דף הבית"))
            if self.chapters:
                first = self.chapters[min(self.chapters)]
                links.append((first.out, f"פרק {first.number}"))
        else:
            links.append((self.front.out, BOOK))
            if doc.kind == "chapter" and doc.number in self.decks:
                links.append((self.decks[doc.number].out, "המצגת"))
            elif doc.kind == "deck" and doc.number in self.chapters:
                links.append((self.chapters[doc.number].out, "הפרק"))
        nav = "".join(f'<a href="{esc(rel_url(doc.out, target))}">{esc(text)}</a>' for target, text in links)
        nav += f'<a href="{REPO_URL}" target="_blank" rel="noopener">GitHub</a>'
        home = esc(rel_url(doc.out, "index.html"))
        bar = '<div class="progress" aria-hidden="true"><span></span></div>' if progress else ""
        return (
            '<a class="skip" href="#content">דילוג לתוכן</a>\n'
            '<header class="top"><div class="top-in">'
            f'<a class="brand" href="{home}" title="{esc(GUIDE)}"><span class="brand-dot" aria-hidden="true"></span>'
            f'<bdi class="brand-name">{SITE}</bdi></a>'
            f'<nav class="top-nav" aria-label="ניווט">{nav}</nav>'
            '<button class="theme" type="button" aria-label="מצב כהה או בהיר" title="מצב כהה או בהיר">'
            f"{ICON_MOON}{ICON_SUN}</button></div>{bar}</header>"
        )

    def site_footer(self, doc: Doc) -> str:
        source = f"{REPO_URL}/blob/main/{quote(doc.src)}"
        book = esc(rel_url(doc.out, self.front.out))
        return (
            f'<footer class="site"><div class="site-in"><span>{esc(AUTHOR_LINE)}</span><span class="site-links">'
            f'<a href="{REPO_URL}" target="_blank" rel="noopener">GitHub</a> · '
            f'<a href="{source}" target="_blank" rel="noopener">מקור העמוד</a> · '
            f'<a href="{book}">{BOOK}</a></span></div></footer>'
        )

    def render_book_page(self, doc: Doc) -> str:
        _, paras, start = self.split_head(doc)
        end, footer = self.split_footer(doc.tokens, start)
        body = doc.tokens[start:end]
        parts = self.head_parts(paras)
        kicker, title = split_title(doc.h1)
        if doc.kind == "front":
            eyebrow = BOOK if kicker in ("", BOOK) else f"{BOOK} · {kicker}"
            if self.chapters:
                first = self.chapters[min(self.chapters)]
                parts["actions"].insert(0, {
                    "primary": True,
                    "title": first.h1,
                    "text": f"מתחילים לקרוא: פרק {first.number}",
                    "href": rel_url(doc.out, first.out),
                })
        else:
            eyebrow = f"{BOOK} · {kicker or 'פרק ' + str(doc.number)}"
        side, mobile = self.tocs(body, "בפרק הזה" if doc.kind == "chapter" else "בעמוד הזה")
        rights = "".join(f'<p class="rights">{self.inline(t)}</p>' for t in footer if t.type == "inline")
        main = "\n".join([
            '<main id="content" class="book">' if side else '<main id="content" class="book no-toc">',
            self.page_head(doc, parts, eyebrow, title),
            side,
            mobile,
            f'<article class="prose">\n{self.blocks(body)}</article>',
            f'<footer class="page-end">\n{rights}{self.pager(doc)}\n</footer>',
            "</main>",
        ])
        name = f"{doc.h1} · {SITE}" if doc.kind == "front" else f"{doc.h1} · {BOOK} · {SITE}"
        return self.page(doc, name, shorten(parts["lead_text"] or doc.h1), main, progress=True)

    def page(self, doc: Doc, title: str, description: str, main: str, progress: bool) -> str:
        url = PAGES_URL + (doc.out[: -len("index.html")] if doc.out.endswith("index.html") else doc.out)
        deck = doc.kind == "deck"
        styles = [self.asset(doc, "assets/book.css")] + ([self.asset(doc, "assets/deck.css")] if deck else [])
        scripts = [self.asset(doc, MERMAID_JS)] if doc.has_diagrams() else []
        scripts.append(self.asset(doc, "assets/book.js"))
        if deck:
            scripts.append(self.asset(doc, "assets/deck.js"))
        lines = [
            "<!DOCTYPE html>",
            f"<!-- {MARKER} from {doc.src}. Do not edit this file: edit the source and render again. -->",
            '<html lang="he" dir="rtl">',
            "<head>",
            '<meta charset="utf-8">',
            '<meta name="viewport" content="width=device-width, initial-scale=1">',
            '<meta name="color-scheme" content="light dark">',
            f"<title>{esc(title)}</title>",
            f'<meta name="description" content="{esc(description)}">',
            f'<link rel="canonical" href="{esc(url)}">',
            '<meta property="og:type" content="article">',
            f'<meta property="og:title" content="{esc(doc.h1)}">',
            f'<meta property="og:description" content="{esc(description)}">',
            f'<meta property="og:url" content="{esc(url)}">',
            '<meta property="og:locale" content="he_IL">',
            f'<meta property="og:site_name" content="{SITE}">',
            f'<link rel="icon" href="{FAVICON}">',
            THEME_INIT,
            *(f'<link rel="stylesheet" href="{esc(href)}">' for href in styles),
            *(f'<script defer src="{esc(src)}"></script>' for src in scripts),
            "</head>",
            f'<body class="page-{doc.kind}">',
            self.top(doc, progress),
            main,
            self.site_footer(doc),
            '<button class="to-top" type="button" aria-label="חזרה לראש העמוד" title="חזרה לראש העמוד">'
            f"{ICON_UP}</button>",
            "</body>",
            "</html>",
            "",
        ]
        return "\n".join(lines)

    # Slide decks.

    def slide_html(self, doc: Doc, slide: Slide, total: int) -> str:
        tokens = slide.tokens
        message, notes, body = "", "", []
        i = 0
        while i < len(tokens):
            token, end = tokens[i], block_end(tokens, i)
            if token.type == "html_block" and COMMENTS.fullmatch(token.content):
                pass
            elif not message and token.type == "paragraph_open" and lead_label(tokens[i + 1]) == "המסר":
                message = self.inline(drop_label(tokens[i + 1]))
            elif token.type == "blockquote_open" and tokens[i + 1].type == "paragraph_open" \
                    and lead_label(tokens[i + 2]) == "הערת דובר":
                inner = tokens[i + 1:end - 1]
                inner[1] = drop_label(inner[1])
                notes += self.blocks(inner)
            else:
                body.extend(tokens[i:end])
            i = end
        cover = slide.number == 1
        out = [
            f'<section class="slide{" cover" if cover else ""}" data-n="{slide.number}" '
            f'aria-label="שקף {slide.number} מתוך {total}">',
            '<div class="slide-in">',
        ]
        if cover:
            out.append(f'<p class="slide-kicker">מפגש {doc.number}</p>')
        out.append(f'<h2 class="slide-title">{self.md.renderInline(slide.title)}</h2>')
        if message:
            out.append(f'<p class="slide-message">{message}</p>')
        out.append(f'<div class="slide-body">\n{self.blocks(body)}</div>')
        out.append(
            f'<div class="slide-foot"><span>{esc(COURSE)} · מפגש {doc.number}</span>'
            f'<span class="slide-num">{slide.number}</span></div>'
        )
        out.append("</div>")
        if notes:
            out.append(
                '<aside class="slide-notes"><p class="slide-notes-title">הערות דובר</p>'
                f'<div class="slide-notes-body">\n{notes}</div></aside>'
            )
        out.append("</section>")
        return "\n".join(out)

    def render_deck(self, doc: Doc) -> str:
        _, paras, _ = self.split_head(doc)
        parts = self.head_parts(paras)
        kicker, title = split_title(doc.h1)
        eyebrow = f"{BOOK} · {kicker or 'מצגת מפגש ' + str(doc.number)}"
        total = len(doc.slides)
        rights = [f'<p class="rights">{self.inline(t)}</p>' for t in doc.footer if t.type == "inline"]
        if not rights:
            rights = [f'<p class="rights">{r}</p>' for r in parts["rights"]]
        actions = "".join(self.button(a) for a in parts["actions"])
        head = ['<header class="deck-head">', '<div class="deck-head-text">', f'<p class="eyebrow">{esc(eyebrow)}</p>',
                f"<h1>{esc(title)}</h1>"]
        if parts["lead"]:
            head.append(f'<p class="deck-lead">{parts["lead"]}</p>')
        head.append("</div>")
        if actions:
            head.append(f'<div class="actions">{actions}</div>')
        head.append("</header>")
        slides = "\n".join(self.slide_html(doc, slide, total) for slide in doc.slides)
        deck = [
            f'<section class="deck" aria-roledescription="מצגת" aria-label="{esc(title)}">',
            '<div class="deck-stage"><div class="deck-viewport">',
            slides,
            "</div></div>",
            '<div class="deck-bar">',
            f'<button class="deck-prev" type="button" aria-label="השקף הקודם" title="השקף הקודם">{ICON_PREV}</button>',
            f'<span class="deck-count" aria-live="polite">שקף <b>1</b> מתוך {total}</span>',
            f'<button class="deck-next" type="button" aria-label="השקף הבא" title="השקף הבא">{ICON_NEXT}</button>',
            '<span class="deck-progress" aria-hidden="true"><span></span></span>',
            f'<button class="deck-notes-toggle" type="button" aria-pressed="true">{ICON_NOTES}<span>הערות דובר</span></button>',
            f'<button class="deck-full" type="button" aria-label="מסך מלא" title="מסך מלא">{ICON_FULL}{ICON_FULL_EXIT}</button>',
            "</div>",
            "</section>",
            '<section class="deck-notes" aria-label="הערות דובר">',
            "<h2>הערות דובר</h2>",
            '<div class="deck-notes-body" aria-live="polite"></div>',
            "</section>",
            '<p class="deck-help"><kbd>חץ שמאלה</kbd> או <kbd>רווח</kbd>: השקף הבא · <kbd>חץ ימינה</kbd>: השקף הקודם'
            " · <kbd>F</kbd>: מסך מלא · <kbd>N</kbd>: הערות דובר</p>",
        ]
        main = "\n".join([
            '<main id="content" class="deck-page">',
            *head,
            *deck,
            '<footer class="page-end">' + "".join(rights) + "</footer>",
            "</main>",
        ])
        name = f"{doc.h1} · {BOOK} · {SITE}"
        return self.page(doc, name, shorten(parts["lead_text"] or doc.h1), main, progress=False)

    def render(self) -> dict[str, str]:
        """Every page of the book: its path from the repository root, and its HTML."""
        return {
            doc.out: self.render_deck(doc) if doc.kind == "deck" else self.render_book_page(doc)
            for doc in self.docs
        }


def generated_pages() -> list[str]:
    """The pages in course/ that this renderer wrote, found by the marker in their first lines."""
    found = []
    for path in sorted((ROOT / "course").rglob("*.html")):
        with path.open(encoding="utf-8", errors="replace") as handle:
            if MARKER in handle.read(400):
                found.append(path.relative_to(ROOT).as_posix())
    return found


def _same(path: Path, text: str) -> bool:
    return path.is_file() and path.read_text(encoding="utf-8").replace("\r\n", "\n") == text


def write() -> list[str]:
    """Render the book, write the pages that changed, remove pages whose source is gone, and report."""
    pages = Book().render()
    report = []
    for out, text in pages.items():
        path = ROOT / out
        if _same(path, text):
            report.append(f"up to date {out}")
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            report.append(f"wrote {out}")
    for out in generated_pages():
        if out not in pages:
            (ROOT / out).unlink()
            report.append(f"removed {out} (its source is gone)")
    return report


def check() -> list[str]:
    """The pages that are missing, out of date, or left behind by a source that is gone."""
    pages = Book().render()
    stale = []
    for out, text in pages.items():
        path = ROOT / out
        if not path.is_file():
            stale.append(f"{out} (missing)")
        elif not _same(path, text):
            stale.append(f"{out} (out of date)")
    stale += [f"{out} (its source is gone)" for out in generated_pages() if out not in pages]
    return stale
